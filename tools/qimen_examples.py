def chk(book, cite, quote):
    k = f"{book}·{cite}"
    if quote not in ENT.get(k, ""):
        raise SystemExit(f"引文不在原文中：{k} ← {quote!r}")
    return {"cite": k, "quote": quote}


def build():
    cases = []
    for cid, cite, quote, dun, ju, hour, day, expect, extra in CASES:
        c = {"id": cid, **chk(YY, cite, quote), "method": "zhuan", "dun": dun, "ju": ju, "hour": hour}
        if day:
            c["day"] = day
        c["expect"] = expect
        c.update(extra)
        cases.append(c)
    for cid, cite, quote, dun, ju, hour, expect in XIEJI:
        cases.append({"id": cid, **chk(XJ, cite, quote), "method": "xieji_fei", "dun": dun, "ju": ju, "hour": hour, "expect": expect})
    runqi = [{"id": i, **chk(b, c, qt), "jieqi": j, "diff": d, "verdict": v} for i, b, c, qt, j, d, v in RUNQI]
    return {
        "note": __doc__.split("\n\n", 1)[1].strip(),
        "provenance": "extracted",
        "cases": cases,
        "runqi": runqi,
    }


def main(check: bool) -> int:
    body = json.dumps(build(), ensure_ascii=False, indent=1) + "\n"
    path = os.path.join(QM, "examples.json")
    if check:
        same = os.path.exists(path) and open(path).read() == body
        print(("一致 " if same else "不一致 ") + "examples.json")
        return 0 if same else 1
    open(path, "w").write(body)
    d = json.loads(body)
    print(f"examples.json: {len(d['cases'])} 例排盘，{len(d['runqi'])} 例定局")
    return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
