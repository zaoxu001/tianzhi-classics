def cut(text, a, b):
    i = text.find(a)
    assert i >= 0, a
    j = text.find(b, i)
    assert j >= 0 and j - i < 3000, b
    return re.sub(r"\n\s*", "", text[i:j + len(b)]).replace("\u3000", "")


def build():
    vols = {}
    items = []
    for key, vol, ch, a, b, about in ITEMS:
        t = vols.setdefault(vol, volume(vol))
        items.append({"key": key, "vol": vol, "chapter": ch, "text": cut(t, a, b), "about": about})
    return {"book": "liurendaquan", "edition": "四库全书本，据维基文库录文", "note": NOTE, "items": items}


if __name__ == "__main__":
    doc = build()
    if "--check" in sys.argv:
        have = json.load(open(OUT))
        bad = [x["key"] for x, y in zip(doc["items"], have["items"]) if x != y]
        same = not bad and len(doc["items"]) == len(have["items"])
        print("一致" if same else f"不一致：{bad}")
        sys.exit(0 if same else 1)
    json.dump(doc, open(OUT, "w"), ensure_ascii=False, indent=1)
    print(len(doc["items"]), "段 →", OUT)
