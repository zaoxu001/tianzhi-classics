def q(cite: str, quote: str) -> dict:
    """引文：cite 为「書名·卷|篇」，quote 必须逐字在该篇原文中"""
    if cite not in ENT:
        raise SystemExit(f"无此条目：{cite}")
    if quote not in ENT[cite]:
        raise SystemExit(f"引文不在原文中：{cite} ← {quote!r}")
    return {"cite": cite, "quote": quote}


